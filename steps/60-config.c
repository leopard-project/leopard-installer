/*
 * steps/60-config.c — 步骤 60：生成目标系统的启动期配置
 *
 * 由 main.c（序列编排器）以全路径、无参数执行。
 * 产出（都在根分区，即 /mnt/system/config/）：
 *   fstab     —— 非根挂载：/apps、/users（fstype 必须 fatfs）
 *   boot.conf —— init= （内核 PID1 路径；引导器 open-xsboot 读取）
 */
#include "li.h"

static const char *field(int i, const char *name, char *key, size_t cap, const char *fallback)
{
        snprintf(key, cap, "part.%d.%s", i, name);

        const char *value = li_state_get(key);
        return (value != NULL && value[0] != '\0') ? value : fallback;
}

static int write_fstab(int count)
{
        char   text[2048];
        size_t used;
        char   path[LI_PATH_LEN];

        used = (size_t)snprintf(text, sizeof(text),
                                "# LeopardOS fstab — generated by leopard-installer (60-config)\n"
                                "# <device> <mountpoint> [fstype]\n");
        for (int i = 0; i < count && used + 128 < sizeof(text); i++) {
                char        key[40];
                const char *node  = field(i, "node", key, sizeof(key), NULL);
                const char *mount = field(i, "mount", key, sizeof(key), NULL);
                const char *fs    = field(i, "fs", key, sizeof(key), "fatfs");
                int         n;

                if (node == NULL || mount == NULL) continue;
                if (strcmp(mount, "/") == 0) continue; /* 根由内核 bound root 挂，不写进 fstab */

                n = snprintf(text + used, sizeof(text) - used, "/dev/%s %s %s\n",
                             node, mount, fs);
                if (n <= 0) break;
                used += (size_t)n;
        }

        snprintf(path, sizeof(path), "%s/system/config/fstab", LI_TARGET);
        if (li_write_text(path, text) != 0) return li_fail("write fstab", 0);

        li_log("wrote %s", path);
        return 0;
}

static int write_boot_conf(void)
{
        const char *init = li_state_get("init");
        char        text[512];
        char        path[LI_PATH_LEN];

        if (init == NULL || init[0] == '\0') init = "/system/leopard/leopard-rc.elf";

        snprintf(text, sizeof(text),
                 "# LeopardOS boot.conf — generated by leopard-installer (60-config)\n"
                 "# init= 指定 PID1；留空则内核回退 /system/leopard/leopard-rc.elf\n"
                 "init=%s\n", init);

        const char *scheme = li_state_get("scheme");
        if (scheme != NULL && (strcmp(scheme, "upstream") == 0 || strcmp(scheme, "modern") == 0)) {
                snprintf(path, sizeof(path), "%s/boot/system/boot.conf", LI_TARGET);
                li_make_dirs(LI_TARGET "/boot/system");
        } else {
                snprintf(path, sizeof(path), "%s/system/boot.conf", LI_TARGET);
        }
        if (li_write_text(path, text) != 0) return li_fail("write boot.conf", 0);

        li_log("wrote %s (init=%s)", path, init);
        return 0;
}

int main(int argc, char *argv[], char *envp[])
{
        int  count;
        char dir[LI_PATH_LEN];

        (void)argc;
        (void)argv;
        (void)envp;

        li_step_begin("Generate fstab / boot.conf");

        count = li_state_get_int("part.count", 0);
        if (count <= 0) return li_step_end(li_fail("no partition in state", 0));

        snprintf(dir, sizeof(dir), "%s/system/config", LI_TARGET);
        li_make_dirs(dir);

        if (write_fstab(count) != 0) return li_step_end(1);
        if (write_boot_conf() != 0) return li_step_end(1);

        return li_step_end(0);
}
